/** Browser-tab title for the matched route (`routePath`) at `pathname`: "Order | Final Retail". Reports share one route, so their own name comes from the reports menu. */
export function pageTitle(routePath: string | undefined, pathname: string) {
  const page = routePath === '/reports/*' ? (reportsMenu.find((r) => r.path === pathname)?.name ?? 'Reports') : PAGE_TITLES[routePath ?? ''];
  return page ? `${page} | ${APP_NAME}` : APP_NAME;
}
